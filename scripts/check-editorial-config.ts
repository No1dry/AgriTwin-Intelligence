import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { configSchema, defaultConfig } from '../lib/editorial/schema.mjs';
import { applySourceOverrides, matchingTopics, matchesKeyword, requestedBriefCounts, loadEditorialConfig } from '../lib/editorial/runtime.mjs';

const config = structuredClone(defaultConfig);
assert.equal(configSchema.safeParse(config).success, true);
assert.equal(configSchema.safeParse({ ...config, secret: 'not-a-real-secret' }).success, false);
assert.equal(configSchema.safeParse({ ...config, notifications: { ...config.notifications, feishu: { tech: 1, finance: 0, politics: 0 } } }).success, false);
assert.equal(matchesKeyword('agency report', 'agent'), false);
assert.equal(matchesKeyword('multi-agent systems', 'multi agent'), true);
assert.equal(matchesKeyword('World Models for Robot Learning', 'world model'), true);
assert.ok(matchingTopics({ title: 'Latent dynamics world model' }, config).some((topic) => topic.id === 'world-model'));
config.researchTopics.find((topic) => topic.id === 'world-model')!.enabled = false;
assert.equal(matchingTopics({ title: 'Latent dynamics world model' }, config).length, 0);
const source = { id: 'demo', name: 'Demo', url: 'https://example.com', type: 'rss' as const, category: 'tech' as const, enabled: true };
config.sourceOverrides.demo = { enabled: false, dailyLimit: 4, priority: 'P0' };
assert.deepEqual(applySourceOverrides([source], config)[0], { ...source, enabled: false, dailyLimit: 4, limit: 4, tier: 'T0' });
assert.throws(() => applySourceOverrides([], config), /unknown source/);
config.notifications.feishu.tech = 8;
assert.deepEqual(requestedBriefCounts(config), { tech: 8, finance: 5, politics: 3 });

const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'brief-policy-'));
const file = path.join(directory, 'profile.json');
fs.writeFileSync(file, JSON.stringify(defaultConfig));
assert.equal(loadEditorialConfig(file)?.name, defaultConfig.name);
fs.writeFileSync(file, '{"schemaVersion": 3}');
assert.throws(() => loadEditorialConfig(file), /Invalid editorial/);

const changed = structuredClone(defaultConfig);
changed.papers.dailyMaximum = 2;
changed.papers.historyDays = 7;
changed.papers.minimumScore = 52;
changed.researchTopics = [{ id: 'new-topic', name: 'Test Robotics', enabled: true, priority: 'P0', weight: 2, keywords: ['testrobotics'], aliases: [], excludeKeywords: [] }];
changed.sourceOverrides['openai-news'] = { enabled: false, dailyLimit: 3 };
changed.notifications.feishu.tech = 6;
changed.daily.webMaximum = 20;
fs.writeFileSync(file, JSON.stringify(changed));
const child = spawnSync(process.execPath, ['--import', 'tsx', '--input-type=module', '-e', `
  import assert from 'node:assert/strict';
  import { sources } from './lib/sources/registry.ts';
  import { assessPaper, selectCuratedPapers } from './lib/papers/curation.ts';
  import { buildDeterministicFallback } from './lib/ai/pipeline.ts';
  import { getDisplayedTechArticles } from './lib/output/render.ts';
  assert.equal(sources.find(s => s.id === 'openai-news').enabled, false);
  const papers = Array.from({length: 4}, (_, i) => ({sourceId:'arxiv-cs-ai', source:'arXiv',title:'Testrobotics experiment '+i,url:'https://arxiv.org/abs/2609.0123'+i,excerpt:'We propose testrobotics. Experiments and benchmarks with open-source code and dataset. '.repeat(4), category:'tech',publishedAt:new Date()}));
  assert.ok(assessPaper(papers[0], sources.find(s => s.id === 'arxiv-cs-ai')).focusTags.includes('Test Robotics'));
  assert.equal(selectCuratedPapers(papers,sources).length,2);
  const news = ['tech','finance','politics'].flatMap(category=>Array.from({length:30},(_,i)=>({sourceId:category==='tech'?'openai-news':category,source:category,title:'Actual '+category+' release '+i,url:'https://example.com/'+category+'/'+i,category,summary:'This is an evidence-backed test summary.',publishedAt:new Date()})));
  const digest = buildDeterministicFallback(news);
  assert.equal(digest.tech_briefs.length,6);
  const displayed = getDisplayedTechArticles([...papers,...news.filter(a=>a.category==='tech')],sources);
  assert.ok(displayed.length<=20);
  assert.ok(displayed.some(a=>a.sourceId==='arxiv-cs-ai'));
`], { cwd: process.cwd(), env: { ...process.env, EDITORIAL_PROFILE_PATH: file }, encoding: 'utf8' });
if (child.status !== 0) throw new Error(child.stderr || child.stdout || 'Runtime integration failed');
fs.rmSync(directory, { recursive: true, force: true });
console.log('Editorial configuration: schema, unknown fields, source overrides, keyword focus, paper limits, message counts and web isolation passed. No model or notification calls.');
